def dump(name: str, data: dict) -> None:
    src = json.loads((CHUNK / f"{name}.json").read_text(encoding="utf-8"))
    if set(data) != set(src):
        missing = set(src) - set(data)
        extra = set(data) - set(src)
        raise SystemExit(f"{name}: missing={sorted(missing)[:10]} extra={sorted(extra)[:10]}")
    # preserve source key order
    ordered = {k: data[k] for k in src}
    out = CHUNK / f"{name}.zh.json"
    with out.open("w", encoding="utf-8") as f:
        json.dump(ordered, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{name}.zh.json keys={len(ordered)} match={len(ordered) == len(src)}")


